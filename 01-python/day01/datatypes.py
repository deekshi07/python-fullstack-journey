# Day 1: Data Types in Python

# Numeric types
integer_val = 42
float_val = 3.14
complex_val = 2 + 3j

# Sequence types
text_val = "Python Fullstack"
list_val = [1, 2, 3, 4]
tuple_val = (1, 2, 3)

# Mapping & Set types
dict_val = {"name": "Alice", "role": "Developer"}
set_val = {1, 2, 3, 3, 2}

# Boolean & None
bool_val = True
none_val = None

# Checking data types using type()
print("integer_val:", integer_val, "-> Type:", type(integer_val))
print("float_val:", float_val, "-> Type:", type(float_val))
print("complex_val:", complex_val, "-> Type:", type(complex_val))
print("text_val:", text_val, "-> Type:", type(text_val))
print("list_val:", list_val, "-> Type:", type(list_val))
print("tuple_val:", tuple_val, "-> Type:", type(tuple_val))
print("dict_val:", dict_val, "-> Type:", type(dict_val))
print("set_val:", set_val, "-> Type:", type(set_val))
print("bool_val:", bool_val, "-> Type:", type(bool_val))
print("none_val:", none_val, "-> Type:", type(none_val))
